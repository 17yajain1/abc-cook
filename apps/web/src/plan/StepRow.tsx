import { STEP_AMOUNT_HINT, STEP_TIME_NOTE, textHasTimePhrase } from '@/lib/stepNote'
import { isServingWaitNode } from '@/library/recipeEdits'

import type { RenderTask } from './derive'
import { EditedTag } from './EditedTag'
import { EmphasisText } from './EmphasisText'
import { PencilIcon } from './editorParts'
import { StepEditorBody } from './StepEditorBody'
import { useStepEdit } from './stepEditContext'

/**
 * R6b: a step's instruction as the recipe page draws it, in a card row or a wait window. With nothing to
 * edit it is the plain paragraph it always was. For a saved recipe it carries the quiet "Edited" tag, the
 * time note and the amount hint, and in the open row it is the editor. The serving-wait node's text is
 * generated by ABC Cook, so it is never editable (Q2) and never tagged.
 */
export function StepInstruction({ task, factor }: { task: RenderTask; factor: number }) {
  const api = useStepEdit()
  const editable = api != null && !isServingWaitNode(task.nodeId)

  if (editable && api.step?.target.nodeId === task.nodeId) {
    return (
      <StepEditorBody
        field={api.step}
        onChange={api.change}
        factorLine={api.factorLine}
        importedText={api.importedSteps.get(task.nodeId) ?? null}
        onRestore={api.importedSteps.has(task.nodeId) ? () => api.restore(task.nodeId) : null}
        writeError={api.writeError}
        onSave={api.save}
        blocked={api.blocked}
        centre={api.landing === task.nodeId}
        onCentred={api.onLanded}
      />
    )
  }

  const edited = editable && api.edited.has(task.nodeId)
  const hint = editable && api.inEdit && api.savedStep?.nodeId === task.nodeId && api.savedStep.amountHint
  return (
    <>
      {task.instruction && (
        <span className="mt-1 block text-[15px] leading-[1.45] text-home-ink">
          <EmphasisText text={task.instruction} consumed={task.consumed} factor={factor} />
          {edited && <EditedTag onClick={() => api.open(task.nodeId)} />}
        </span>
      )}
      {edited && textHasTimePhrase(task.instruction) && (
        <span className="mt-0.5 block text-[13px] leading-[1.4] text-home-ink-2">{STEP_TIME_NOTE}</span>
      )}
      {hint && <span className="mt-0.5 block text-[13px] leading-[1.4] text-home-ink-2">{STEP_AMOUNT_HINT}</span>}
    </>
  )
}

/** The pencil on an editable step in edit mode, under its duration (Q5 (a)). Nothing otherwise. */
export function StepPencil({ task }: { task: RenderTask }) {
  const api = useStepEdit()
  if (!api || !api.inEdit || isServingWaitNode(task.nodeId) || api.step?.target.nodeId === task.nodeId) return null
  return (
    <button
      type="button"
      aria-label={`Edit step: ${task.label}`}
      onClick={() => api.open(task.nodeId)}
      className="mt-1 flex h-11 w-11 items-center justify-end text-home-ink"
    >
      <PencilIcon />
    </button>
  )
}
